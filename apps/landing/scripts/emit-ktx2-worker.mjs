/**
 * Emit the KTX2 transcoder worker as a real, same-origin file.
 *
 * three's KTX2Loader builds this worker by concatenating the Basis transcoder
 * with its own worker body and handing the result to `URL.createObjectURL`. A
 * blob: worker inherits the creating document's Content-Security-Policy, and the
 * Emscripten transcoder needs to evaluate a string to start — so the only way to
 * run it under a blob was to allow 'unsafe-eval' for the entire site.
 *
 * A worker fetched from an http(s) URL takes its CSP from its own response
 * headers instead. Emitting the identical body to a fixed path lets vercel.json
 * grant 'unsafe-eval' to that one file and nothing else, which is what keeps the
 * document's policy strict while the room still gets its textures.
 *
 * The body is assembled exactly the way KTX2Loader.init does it. Generated at
 * build time rather than committed, so a three upgrade cannot leave a stale copy
 * behind — the guard in tests/build/experience-effects-guards.mjs checks it was
 * produced from the installed version.
 */
import { readFileSync, mkdirSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { dirname, join } from 'node:path'
import { KTX2Loader } from 'three/examples/jsm/loaders/KTX2Loader.js'

const require = createRequire(import.meta.url)
const basisDir = dirname(require.resolve('three/examples/jsm/libs/basis/basis_transcoder.js'))
const transcoder = readFileSync(join(basisDir, 'basis_transcoder.js'), 'utf8')

const fn = KTX2Loader.BasisWorker.toString()
const body = [
  '/* Generated by scripts/emit-ktx2-worker.mjs — do not edit. */',
  '/* constants */',
  'let _EngineFormat = ' + JSON.stringify(KTX2Loader.EngineFormat),
  'let _EngineType = ' + JSON.stringify(KTX2Loader.EngineType),
  'let _TranscoderFormat = ' + JSON.stringify(KTX2Loader.TranscoderFormat),
  'let _BasisFormat = ' + JSON.stringify(KTX2Loader.BasisFormat),
  '/* basis_transcoder.js */',
  transcoder,
  '/* worker */',
  fn.substring(fn.indexOf('{') + 1, fn.lastIndexOf('}')),
].join('\n')

const target = 'public/archive-basis/ktx2-worker.js'
mkdirSync(dirname(target), { recursive: true })
writeFileSync(target, body)
console.log(`[emit-ktx2-worker] ${target} ${(body.length / 1024).toFixed(1)} KB`)
